-- ---------- แอดมิน ----------
create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.admins enable row level security;   -- ไม่มี policy = เข้าตรงๆไม่ได้ ใช้ผ่านฟังก์ชันเท่านั้น

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins where user_id = auth.uid())
$$;

-- ---------- โปรไฟล์สมาชิก ----------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default '',
  phone text not null default '',
  address text not null default ''
);
alter table public.profiles enable row level security;

create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, name, phone)
  values (new.id, coalesce(new.raw_user_meta_data->>'name',''), coalesce(new.raw_user_meta_data->>'phone',''))
  on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

drop policy if exists profiles_select on public.profiles;
drop policy if exists profiles_update on public.profiles;
create policy profiles_select on public.profiles for select using (id = auth.uid() or public.is_admin());
create policy profiles_update on public.profiles for update using (id = auth.uid() or public.is_admin())
  with check (id = auth.uid() or public.is_admin());

-- ---------- สินค้า ----------
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  cat text not null default 'Accessories',
  brand text not null default 'Generic',
  name text not null,
  spec text not null default '',
  price integer not null check (price >= 0),
  orig integer not null default 0,
  grade text not null default 'B',
  icon text not null default 'package',
  warranty integer not null default 0,
  stock integer not null default 0 check (stock >= 0),
  tested text not null default '',
  flaws text not null default '',
  grade_label text not null default '',
  grade_desc text not null default '',
  imgs jsonb not null default '[]'::jsonb,
  img text not null default '',
  deleted boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.products enable row level security;
drop policy if exists products_select on public.products;
drop policy if exists products_admin_all on public.products;
create policy products_select on public.products for select using (not deleted or public.is_admin());
create policy products_admin_all on public.products for all using (public.is_admin()) with check (public.is_admin());

-- ---------- คำสั่งซื้อ ----------
