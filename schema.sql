-- สั่งซื้อ: ตัดสต็อก + คิดราคาจากราคาจริงในฐานข้อมูล (ไม่เชื่อราคาจากเบราว์เซอร์)
create or replace function public.place_order(p_items jsonb, p_customer jsonb, p_payment text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  it jsonb; pid bigint; q int; prod public.products%rowtype;
  lines jsonb := '[]'::jsonb; sub int := 0; ship int; fee int; total int; oid uuid;
  cname text := trim(coalesce(p_customer->>'name','')); cphone text := trim(coalesce(p_customer->>'phone',''));
  caddr text := trim(coalesce(p_customer->>'address',''));
begin
  if auth.uid() is null then raise exception 'NOT_AUTHENTICATED'; end if;
  if p_payment is null or p_payment not in ('transfer','promptpay','cod') then raise exception 'INVALID_PAYMENT'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'EMPTY_CART'; end if;
  if length(cname) < 2 or length(cphone) < 9 or length(caddr) < 10 then raise exception 'INVALID_CUSTOMER'; end if;

  for it in select * from jsonb_array_elements(p_items) loop
    pid := (it->>'id')::bigint; q := (it->>'qty')::int;
    if q is null or q < 1 or q > 99 then raise exception 'INVALID_QTY'; end if;
    select * into prod from public.products where id = pid and not deleted for update;
    if not found or prod.stock < q then raise exception 'OUT_OF_STOCK:%', pid; end if;
    update public.products set stock = stock - q where id = pid;
    sub := sub + prod.price * q;
    lines := lines || jsonb_build_object('id', pid, 'name', prod.name, 'price', prod.price, 'qty', q);
  end loop;

  ship  := case when sub = 0 or sub >= 2000 then 0 else 80 end;   -- ต้องตรงกับ SHIP_FREE / SHIP_FEE ใน config.js
  fee   := case when p_payment = 'cod' then 30 else 0 end;        -- ต้องตรงกับ COD_FEE ใน config.js
  total := sub + ship + fee;

  insert into public.orders (user_id, customer, items, payment, total)
  values (auth.uid(), jsonb_build_object('name', cname, 'phone', cphone, 'address', caddr), lines, p_payment, total)
  returning id into oid;
  return jsonb_build_object('orderId', oid, 'total', total);
end $$;

-- แนบสลิป (เจ้าของออเดอร์เท่านั้น)
create or replace function public.attach_slip(p_id uuid, p_slip text) returns void
language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then raise exception 'NOT_AUTHENTICATED'; end if;
  if p_slip is null or length(p_slip) > 3000000 then raise exception 'ไฟล์สลิปใหญ่เกินไป'; end if;
  update public.orders set slip = p_slip where id = p_id and user_id = auth.uid();
  if not found then raise exception 'ไม่พบคำสั่งซื้อ'; end if;
end $$;

-- ติดตามพัสดุ: ต้องรู้ทั้งรหัสออเดอร์และเบอร์โทร ไม่เปิดเผยที่อยู่
create or replace function public.track_order(p_code text, p_phone text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare o public.orders%rowtype; ph text := regexp_replace(coalesce(p_phone,''), '\D', '', 'g');
begin
  if length(ph) < 9 then return null; end if;
  select * into o from public.orders
   where ( 'ORD-' || upper(left(replace(id::text,'-',''), 6)) = upper(trim(coalesce(p_code,'')))
        or upper(id::text) = upper(trim(coalesce(p_code,''))) )
     and regexp_replace(coalesce(customer->>'phone',''), '\D', '', 'g') = ph
   limit 1;
  if not found then return null; end if;
  return jsonb_build_object('status', o.status, 'ship', o.ship, 'created_at', o.created_at,
    'items', (select coalesce(jsonb_agg((i->>'name') || ' × ' || (i->>'qty')), '[]'::jsonb) from jsonb_array_elements(o.items) i));
end $$;

-- สถิติหน้าแรก
create or replace function public.sales_stats() returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'sold', coalesce((select sum((i->>'qty')::int) from public.orders o, jsonb_array_elements(o.items) i where o.status <> 'cancelled'), 0),
    'customers', (select count(distinct coalesce(nullif(customer->>'phone',''), user_id::text)) from public.orders where status <> 'cancelled'),
    'revenue', coalesce((select sum(total) from public.orders where status <> 'cancelled'), 0))
$$;

-- ส่งรีวิว (เข้าสถานะรออนุมัติเสมอ)
create or replace function public.add_review(p jsonb) returns void
language plpgsql security definer set search_path = public as $$
declare r int := coalesce((p->>'rating')::int, 0);
begin
  if length(trim(coalesce(p->>'name',''))) < 2 or length(trim(coalesce(p->>'text',''))) < 5 then raise exception 'ข้อมูลรีวิวไม่ครบ'; end if;
  if r < 1 or r > 5 then raise exception 'ให้คะแนน 1-5 ดาว'; end if;
  if length(coalesce(p->>'img','')) > 1500000 then raise exception 'รูปใหญ่เกินไป'; end if;
  insert into public.reviews (status, data) values ('pending', jsonb_build_object(
    'name', left(trim(p->>'name'), 60), 'rating', r, 'product', left(coalesce(p->>'product',''), 100),
    'text', left(trim(p->>'text'), 1000), 'img', coalesce(p->>'img','')));
end $$;

-- ฝากขาย: ลูกค้าส่ง / เช็กสถานะด้วยรหัส + เบอร์
create or replace function public.submit_consign(p jsonb) returns text
language plpgsql security definer set search_path = public as $$
declare cid uuid := gen_random_uuid(); c text;
begin
  if length(trim(coalesce(p->>'seller',''))) < 2 or length(trim(coalesce(p->>'name',''))) < 2 then raise exception 'ข้อมูลไม่ครบ'; end if;
  if length(regexp_replace(coalesce(p->>'phone',''), '\D', '', 'g')) < 9 then raise exception 'เบอร์โทรไม่ถูกต้อง'; end if;
  if length(p::text) > 8000000 then raise exception 'รูปใหญ่เกินไป ลองลดจำนวนรูป'; end if;
  c := 'CS-' || upper(left(replace(cid::text,'-',''), 6));
  insert into public.consign (id, code, phone, data) values (cid, c, trim(p->>'phone'), jsonb_build_object(
    'seller', left(trim(p->>'seller'), 80), 'phone', trim(p->>'phone'), 'name', left(trim(p->>'name'), 120),
    'brand', left(coalesce(p->>'brand','Generic'), 60), 'cat', coalesce(p->>'cat','Accessories'), 'grade', coalesce(p->>'grade','B'),
    'price', coalesce((p->>'price')::int, 0), 'notes', left(coalesce(p->>'notes',''), 1000),
    'imgs', coalesce(p->'imgs', '[]'::jsonb), 'commission', p->'commission'));
  return c;
end $$;

create or replace function public.consign_status(p_code text, p_phone text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare r public.consign%rowtype; ph text := regexp_replace(coalesce(p_phone,''), '\D', '', 'g');
begin
  if length(ph) < 9 then return null; end if;
  select * into r from public.consign where upper(code) = upper(trim(coalesce(p_code,''))) and regexp_replace(phone, '\D', '', 'g') = ph limit 1;
  if not found then return null; end if;
  return jsonb_build_object('status', r.status, 'product', r.data->>'name', 'price', r.data->'price',
    'commission', r.data->'commission', 'reason', coalesce(r.data->>'reason',''), 'created_at', r.created_at);
end $$;

-- แอดมิน: บันทึกเลขพัสดุ
create or replace function public.admin_set_shipping(p_id uuid, p_ship jsonb) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'NOT_ADMIN'; end if;
  update public.orders set
    ship = jsonb_build_object('carrier', p_ship->>'carrier', 'no', p_ship->>'no', 'at', (extract(epoch from now()) * 1000)::bigint),
    status = case when status in ('pending','paid') then 'shipped' else status end
  where id = p_id;
  if not found then raise exception 'ไม่พบคำสั่งซื้อ'; end if;
end $$;

-- แอดมิน: แก้ข้อมูลลูกค้า (ทุกออเดอร์ของลูกค้าคนนั้น + บัญชีสมาชิก)
create or replace function public.admin_update_customer(p_old_phone text, p_old_name text, p_name text, p_phone text, p_address text)
returns int language plpgsql security definer set search_path = public as $$
declare n int;
begin
  if not public.is_admin() then raise exception 'NOT_ADMIN'; end if;
  update public.orders set customer = coalesce(customer, '{}'::jsonb) || jsonb_build_object('name', p_name, 'phone', p_phone, 'address', p_address)
   where (coalesce(p_old_phone,'') <> '' and regexp_replace(coalesce(customer->>'phone',''), '\D', '', 'g') = p_old_phone)
      or (coalesce(p_old_phone,'') = '' and regexp_replace(coalesce(customer->>'phone',''), '\D', '', 'g') = '' and customer->>'name' = p_old_name);
  get diagnostics n = row_count;
  if coalesce(p_old_phone,'') <> '' then
    update public.profiles set name = p_name, phone = p_phone, address = p_address
     where regexp_replace(phone, '\D', '', 'g') = p_old_phone;
  end if;
  return n;
end $$;

